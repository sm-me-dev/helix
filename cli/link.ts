// `helix link` / `helix unlink`: put a `helix` command on the user's PATH.
// The shim is a tiny POSIX script that points at this checkout (the CLI needs the repo's
// node_modules, so a copy would not work). Nothing here edits a file the user did not
// create or that does not carry the Helix marker.
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, delimiter, join, resolve } from "node:path";

const SHIM_MARKER = "helix-shim";
const RC_START = "# >>> helix >>>";
const RC_END = "# <<< helix <<<";

/** POSIX single-quote escaping. */
function sq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export function shimScript(o: { cliPath: string; nodePath: string }): string {
  // Prefer the node on PATH at run time (nvm/fnm switch versions); fall back to the one that
  // ran `helix link` so the shim still works from a minimal environment.
  return [
    "#!/bin/sh",
    `# ${SHIM_MARKER}: generated by \`helix link\`; remove with \`helix unlink\``,
    `NODE="$(command -v node 2>/dev/null || true)"`,
    `[ -n "$NODE" ] || NODE=${sq(o.nodePath)}`,
    `exec "$NODE" --experimental-strip-types --disable-warning=ExperimentalWarning ${quoteIfNeeded(o.cliPath)} "$@"`,
    "",
  ].join("\n");
}

/** Plain double quotes when safe (keeps the common case readable), single-quote escaping otherwise. */
function quoteIfNeeded(p: string): string {
  return /^[A-Za-z0-9_@%+=:,./-]+$/.test(p) ? `"${p}"` : sq(p);
}

export type ShimResult = { path: string; action: "wrote" | "kept" | "refused" };

export function installShim(o: {
  binDir: string;
  cliPath: string;
  nodePath: string;
  force?: boolean;
}): ShimResult {
  const path = join(o.binDir, "helix");
  const content = shimScript({ cliPath: resolve(o.cliPath), nodePath: o.nodePath });
  if (existsSync(path)) {
    const current = readFileSync(path, "utf8");
    if (current === content) return { path, action: "kept" };
    if (!current.includes(SHIM_MARKER) && !o.force) return { path, action: "refused" };
  }
  mkdirSync(o.binDir, { recursive: true });
  writeFileSync(path, content);
  chmodSync(path, 0o755);
  return { path, action: "wrote" };
}

export function removeShim(o: { binDir: string }): {
  path: string;
  action: "removed" | "absent" | "refused";
} {
  const path = join(o.binDir, "helix");
  if (!existsSync(path)) return { path, action: "absent" };
  if (!readFileSync(path, "utf8").includes(SHIM_MARKER)) return { path, action: "refused" };
  rmSync(path);
  return { path, action: "removed" };
}

export function isOnPath(dir: string, pathVar: string | undefined): boolean {
  const norm = (d: string) => (d.length > 1 ? d.replace(/\/+$/, "") : d);
  return (pathVar ?? "").split(delimiter).some((d) => d !== "" && norm(d) === norm(dir));
}

/** rc file for the user's login shell, or null when we cannot edit it safely (fish, unknown). */
export function rcFileFor(shell: string | undefined, home: string): string | null {
  const name = shell ? basename(shell) : "";
  if (name === "zsh") return join(home, ".zshrc");
  if (name === "bash") return join(home, ".bashrc");
  return null;
}

export function addRcBlock(rcPath: string, binDir: string): "added" | "kept" {
  const current = existsSync(rcPath) ? readFileSync(rcPath, "utf8") : "";
  if (current.includes(RC_START)) return "kept";
  const sep = current === "" || current.endsWith("\n") ? "" : "\n";
  const block = `${RC_START}\nexport PATH="${binDir}:$PATH"\n${RC_END}\n`;
  writeFileSync(rcPath, current + sep + block);
  return "added";
}

export function removeRcBlock(rcPath: string): "removed" | "absent" {
  if (!existsSync(rcPath)) return "absent";
  const current = readFileSync(rcPath, "utf8");
  const start = current.indexOf(RC_START);
  const end = current.indexOf(RC_END);
  if (start === -1 || end === -1 || end < start) return "absent";
  const after = current.slice(end + RC_END.length).replace(/^\n/, "");
  writeFileSync(rcPath, current.slice(0, start) + after);
  return "removed";
}
